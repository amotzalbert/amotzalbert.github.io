const wazeUrl = (t) => `https://waze.com/ul?ll=${t.lat},${t.lon}&navigate=yes`;
const gmapUrl = (t) =>
  `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(t.name)}`;
